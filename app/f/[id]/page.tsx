import Link from "next/link";
import { notFound } from "next/navigation";
import type { Metadata } from "next";

import { createClient } from "@/lib/supabase/server";
import { Nub } from "@/components/Nub";
import { ShareButton } from "@/components/ShareButton";
import { Wordmark } from "@/components/Wordmark";
import { findPhotoUrl, findSummary, findUrl, formatDollars, savedAmount } from "@/lib/finds";
import { formatSaleDay } from "@/lib/sale-time";

/**
 * One find, for a stranger.
 *
 * This is the growth loop's landing page (CLAUDE.md §6): somebody sends the
 * link to a group chat, and whoever opens it has never heard of XLResale. So
 * the page is built for that reader rather than for the finder — the bargain
 * first, then who found it, then the one thing to do next.
 *
 * Public by RLS, not by a check here: `finds_public_read` only returns rows
 * with `is_public = true`, so a private find is simply not found. That means a
 * finder toggling a find back to private breaks the link they shared, which is
 * the correct behaviour and the reason the toggle says what it says.
 */

async function loadFind(id: string) {
  const supabase = await createClient();

  const { data: find } = await supabase
    .from("finds")
    .select("id, finder_id, sale_id, title, note, price_paid, est_value, photo_path, found_on")
    .eq("id", id)
    .maybeSingle();

  if (!find) return null;

  // public_profiles only lists profiles that opted in, so a public find by a
  // private profile comes back unattributed. The find was made public; the
  // person wasn't.
  const [{ data: finder }, { data: sale }] = await Promise.all([
    supabase.from("public_profiles").select("username").eq("id", find.finder_id).maybeSingle(),
    find.sale_id
      ? supabase.from("public_sales").select("id, title").eq("id", find.sale_id).maybeSingle()
      : Promise.resolve({ data: null }),
  ]);

  return { find, finder, sale };
}

export async function generateMetadata({ params }: PageProps<"/f/[id]">): Promise<Metadata> {
  const { id } = await params;
  const loaded = await loadFind(id);

  if (!loaded) return { title: "Find not found — XLResale" };

  const { find, finder } = loaded;
  const title = finder?.username ? `${find.title} — @${finder.username}` : find.title;
  const description = findSummary(find);

  return {
    title: `${title} — XLResale`,
    description,
    // Absolute, because these are read by a machine on another host. The image
    // itself is generated by opengraph-image.tsx next door.
    openGraph: {
      title,
      description,
      url: findUrl(id),
      type: "article",
      siteName: "XLResale",
    },
    twitter: { card: "summary_large_image", title, description },
  };
}

